// Soal nomor 1
const nama = "Doni"; // Variabel nama menggunakan String ""
const umur = 15; // Variabel umur menggunakan Number
const isStudent = true; // Variabel isStudent (Boolean) yang bernilai true atau false

// best practice menggunakan operator literal seperti (``) bukan menggunakan (+)
const identitas = 'Halo nama saya ' + nama + '\n' + 'Umur saya ' + umur + '\n' + 'Saya adalah murid ' + isStudent; // Variabel identitas untuk menampilkan semua variabel yang sudah di deklarasikan sebelumnya
console.log(identitas); // Menampilkan semua variabel dari melalui variabel identitas

// Soal nomor 2
const x = 33;
const y = 18;
console.log(x * y); //kali
console.log(x / y); //bagi
console.log(x + y); //tambah
console.log(x - y); //kurang
console.log(x % y); //sisa bagi (modulus)
console.log(x ** 3); //pangkat

